-- Атомарная замена набора ниш у крео (одна транзакция; конкурентные вызовы не оставляют
-- «полусостояния» — последний победивший набор целиком).
create or replace function public.set_creo_niches(p_creo_id bigint, p_niche_ids bigint[], p_by bigint default null)
returns bigint[]
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ids bigint[];
begin
  -- только существующие ниши, без дублей
  select coalesce(array_agg(distinct n.id order by n.id), '{}')
    into v_ids
    from unnest(coalesce(p_niche_ids, '{}')) as u(id)
    join public.niches n on n.id = u.id;
  delete from public.creo_niches where creo_id = p_creo_id and not (niche_id = any (v_ids));
  insert into public.creo_niches (creo_id, niche_id, added_by_tg_id)
    select p_creo_id, x, p_by from unnest(v_ids) as x
    on conflict do nothing;
  return v_ids;
end;
$$;
revoke all on function public.set_creo_niches(bigint, bigint[], bigint) from public, anon, authenticated;
grant execute on function public.set_creo_niches(bigint, bigint[], bigint) to service_role;

-- updated_at ниши при переименовании
create or replace function public.niches_touch_updated_at()
returns trigger language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists niches_touch_updated_at on public.niches;
create trigger niches_touch_updated_at
  before update on public.niches
  for each row execute function public.niches_touch_updated_at();
