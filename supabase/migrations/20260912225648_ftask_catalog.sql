-- ---------------------------------------------------------------- ниши
create table if not exists public.niches (
  id               bigint generated by default as identity primary key,
  name             text        not null,
  -- ключ уникальности: без регистра и краевых пробелов («Косплей» = «косплей » — одно и то же)
  name_key         text        generated always as (lower(btrim(name))) stored,
  created_by_tg_id bigint,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  constraint niches_name_not_blank check (btrim(name) <> ''),
  constraint niches_name_len check (char_length(name) <= 60)
);
create unique index if not exists niches_name_key_uidx on public.niches (name_key);

create table if not exists public.creo_niches (
  creo_id   bigint not null references public.creos (id) on delete cascade,
  niche_id  bigint not null references public.niches (id) on delete cascade,
  added_by_tg_id bigint,
  added_at  timestamptz not null default now(),
  primary key (creo_id, niche_id)
);
create index if not exists creo_niches_niche_idx on public.creo_niches (niche_id);

